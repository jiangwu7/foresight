"""
Build the Foresight brand kit from the chosen logo mark (spec §13.2).

Source: the Ideogram vector mark `concepts/round2/ideogram/i304_soft_friendly.svg` chosen by the team lead
on 2026-11-03. This script turns that one SVG into everything the project needs, deterministically, so the
kit can be regenerated by anyone:

  assets/brand/logo/            clean transparent SVG mark (amber / off-white / ink) + PNGs 48..1024 px
  assets/brand/logo/lockups     wordmark "Foresight" set in Be Vietnam Pro SemiBold (outlined to paths,
                                never generated as an image) in horizontal and stacked lockups, SVG + PNG
  app/app/src/main/res/mipmap-* adaptive launcher icon (foreground, monochrome), legacy icons, 512 px store icon
  dashboard/favicon.svg, favicon-32.png, apple-touch-icon.png
  assets/brand/palette.md       the palette with WCAG contrast ratios (mirrors app/.../ui/theme/Color.kt)

Run from the repo root:  .venv/Scripts/python assets/brand/build_brand_kit.py
Requires: resvg-py, fonttools, pillow (all in the .venv).
"""
from __future__ import annotations

import io
import re
from pathlib import Path

import resvg_py
from PIL import Image
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets/brand/concepts/round2/ideogram/i304_soft_friendly.svg"
OUT = ROOT / "assets/brand/logo"
RES = ROOT / "app/app/src/main/res"
DASH = ROOT / "dashboard"
FONT = RES / "font/be_vietnam_pro_semibold.ttf"

# Brand colors. Keep in sync with app/app/src/main/java/org/jameslick/foresight/ui/theme/Color.kt
AMBER = "#F3B661"      # exact fill of the chosen mark
BONE = "#F5F1E8"
INK = "#0B0D10"
CHARCOAL = "#14171C"
ASH = "#A9A49A"
HAIRLINE = "#2B3038"
AMBER_DEEP = "#9A7030"
OUTCOME = {"green": "#6FA882", "yellow": "#D4B25A", "red": "#C9645B"}
LIGHT = {"background": "#F7F4EE", "surface": "#FFFFFF", "ink": "#14171C", "ash": "#5B5750", "accent": "#7A4E0E",
         "green": "#2F6B45", "yellow": "#7A5C00", "red": "#9B3A32"}


# ----------------------------------------------------------------------------------------------
# 1. Parse the source mark: path 1 = outer eye, path 2 = its dark interior (becomes a hole),
#    paths 3-7 = four shutter blades + center dot. Paths 0, 8, 9 are the background and edge slivers.
# ----------------------------------------------------------------------------------------------
def parse_source():
    paths = re.findall(r'<path fill="([^"]+)" d="([^"]+)"', SRC.read_text(encoding="utf-8"))
    outer, inner = paths[1][1], paths[2][1]
    blades = [d for _, d in paths[3:8]]
    return outer, inner, blades


def bbox(d: str):
    nums = [float(x) for x in re.findall(r"-?\d+\.?\d*", d)]
    xs, ys = nums[0::2], nums[1::2]
    return min(xs), min(ys), max(xs), max(ys)


class Mark:
    def __init__(self):
        self.outer, self.inner, self.blades = parse_source()
        self.x0, self.y0, self.x1, self.y1 = bbox(self.outer)
        self.w, self.h = self.x1 - self.x0, self.y1 - self.y0
        self.cx, self.cy = (self.x0 + self.x1) / 2, (self.y0 + self.y1) / 2

    def body(self, color: str, transform: str = "") -> str:
        t = f' transform="{transform}"' if transform else ""
        parts = [f'<path fill="{color}" fill-rule="evenodd" d="{self.outer} {self.inner}"/>']
        parts += [f'<path fill="{color}" d="{d}"/>' for d in self.blades]
        return f"<g{t}>" + "".join(parts) + "</g>"

    def svg(self, color: str, pad: float = 0.08, square: bool = False, background: str | None = None,
            radius_frac: float = 0.0) -> str:
        """The mark alone, cropped to its bounds plus padding. `square` centers it in a square canvas."""
        if square:
            side = max(self.w, self.h) * (1 + 2 * pad)
            vx, vy, vw, vh = self.cx - side / 2, self.cy - side / 2, side, side
        else:
            px, py = self.w * pad, self.h * pad
            vx, vy, vw, vh = self.x0 - px, self.y0 - py, self.w + 2 * px, self.h + 2 * py
        bg = ""
        if background:
            r = radius_frac * min(vw, vh)
            bg = f'<rect x="{vx:.2f}" y="{vy:.2f}" width="{vw:.2f}" height="{vh:.2f}" rx="{r:.2f}" fill="{background}"/>'
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vx:.2f} {vy:.2f} {vw:.2f} {vh:.2f}" '
                f'width="{vw:.0f}" height="{vh:.0f}">{bg}{self.body(color)}</svg>')

    def placed(self, color: str, canvas: float, width_frac: float, dx: float = 0.0, dy: float = 0.0) -> str:
        """Group that draws the mark centered on a canvas of `canvas` units, scaled to width_frac of it."""
        s = canvas * width_frac / self.w
        tx = canvas / 2 + dx - self.cx * s
        ty = canvas / 2 + dy - self.cy * s
        return self.body(color, f"translate({tx:.3f} {ty:.3f}) scale({s:.6f})")


# ----------------------------------------------------------------------------------------------
# 2. Rendering helpers
# ----------------------------------------------------------------------------------------------
def render_png(svg: str, width: int, height: int | None = None) -> bytes:
    data = resvg_py.svg_to_bytes(svg_string=svg, width=width, height=height or width)
    return bytes(data)


def write(path: Path, data: str | bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, str):
        path.write_text(data, encoding="utf-8")
    else:
        path.write_bytes(data)
    print("wrote", path.relative_to(ROOT))


# ----------------------------------------------------------------------------------------------
# 3. Wordmark: outline "Foresight" from the real font file (spec §13.2: never generate type as an image)
# ----------------------------------------------------------------------------------------------
def wordmark_path(text: str, size: float, tracking: float = 0.0):
    """Returns (svg path d, width) for `text` at `size` units tall (em), baseline at y=0, x from 0."""
    font = TTFont(str(FONT))
    upem = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    scale = size / upem
    pen = SVGPathPen(glyphs)
    x = 0.0
    for ch in text:
        name = cmap[ord(ch)]
        tpen = TransformPen(pen, (scale, 0, 0, -scale, x, 0))
        glyphs[name].draw(tpen)
        x += hmtx[name][0] * scale + tracking
    return pen.getCommands(), x - tracking


def lockup_svg(mark: Mark, stacked: bool, mark_color: str = AMBER, text_color: str = BONE,
               background: str | None = None) -> str:
    text_size = 1000.0
    d, text_w = wordmark_path("Foresight", text_size, tracking=-4.0)
    cap = 0.72 * text_size          # approx cap height of Be Vietnam Pro
    if not stacked:
        mark_h = cap * 1.55
        s = mark_h / mark.h
        mark_w = mark.w * s
        gap = 0.32 * cap
        pad = 0.35 * cap
        W = pad + mark_w + gap + text_w + pad
        H = mark_h + 2 * pad
        tx = pad - mark.x0 * s
        ty = pad - mark.y0 * s
        text_x = pad + mark_w + gap
        text_y = pad + mark_h / 2 + cap / 2          # baseline so caps are vertically centered on the mark
    else:
        mark_w = text_w * 0.42
        s = mark_w / mark.w
        mark_h = mark.h * s
        gap = 0.45 * cap
        pad = 0.4 * cap
        W = text_w + 2 * pad
        H = pad + mark_h + gap + cap + 0.25 * cap + pad
        tx = W / 2 - mark.cx * s
        ty = pad - mark.y0 * s
        text_x = pad
        text_y = pad + mark_h + gap + cap
    bg = f'<rect width="{W:.1f}" height="{H:.1f}" fill="{background}"/>' if background else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.1f} {H:.1f}" width="{W:.0f}" height="{H:.0f}">{bg}'
            f'{mark.body(mark_color, f"translate({tx:.3f} {ty:.3f}) scale({s:.6f})")}'
            f'<path fill="{text_color}" transform="translate({text_x:.3f} {text_y:.3f})" d="{d}"/></svg>')


# ----------------------------------------------------------------------------------------------
# 4. Contrast (WCAG 2.x)
# ----------------------------------------------------------------------------------------------
def luminance(hex_color: str) -> float:
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in (r, g, b)]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(fg: str, bg: str) -> float:
    a, b = luminance(fg), luminance(bg)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def palette_md() -> str:
    rows = [
        ("Dark: body text (Bone) on Ink", BONE, INK, 4.5),
        ("Dark: body text (Bone) on Charcoal card", BONE, CHARCOAL, 4.5),
        ("Dark: secondary text (Ash) on Ink", ASH, INK, 4.5),
        ("Dark: secondary text (Ash) on Charcoal", ASH, CHARCOAL, 4.5),
        ("Dark: accent (Amber) on Ink", AMBER, INK, 4.5),
        ("Dark: text on accent button (Ink on Amber)", INK, AMBER, 4.5),
        ("Dark: outcome green on Charcoal (icon + ≥24sp)", OUTCOME["green"], CHARCOAL, 3.0),
        ("Dark: outcome yellow on Charcoal (icon + ≥24sp)", OUTCOME["yellow"], CHARCOAL, 3.0),
        ("Dark: outcome red on Charcoal (icon + ≥24sp)", OUTCOME["red"], CHARCOAL, 3.0),
        ("Dark: hairline on Ink (non-text, 3:1 not required)", HAIRLINE, INK, 1.0),
        ("Light: body text on background", LIGHT["ink"], LIGHT["background"], 4.5),
        ("Light: body text on surface", LIGHT["ink"], LIGHT["surface"], 4.5),
        ("Light: secondary text on background", LIGHT["ash"], LIGHT["background"], 4.5),
        ("Light: accent on surface", LIGHT["accent"], LIGHT["surface"], 4.5),
        ("Light: white text on accent button", LIGHT["surface"], LIGHT["accent"], 4.5),
        ("Light: outcome green on surface", LIGHT["green"], LIGHT["surface"], 4.5),
        ("Light: outcome yellow on surface", LIGHT["yellow"], LIGHT["surface"], 4.5),
        ("Light: outcome red on surface", LIGHT["red"], LIGHT["surface"], 4.5),
    ]
    lines = ["# Foresight palette (derived from the logo mark, spec §13.2)", "",
             "Generated by `assets/brand/build_brand_kit.py`. Source of truth for the app is",
             "`app/app/src/main/java/org/jameslick/foresight/ui/theme/Color.kt`; keep the two in sync.", "",
             "| Token | Hex | Role |", "|---|---|---|",
             f"| Ink | `{INK}` | app background (near-black, never pure #000) |",
             f"| Charcoal | `{CHARCOAL}` | cards |",
             f"| Hairline | `{HAIRLINE}` | 1dp rules and borders |",
             f"| Amber | `{AMBER}` | the single luminous accent; the logo's exact color |",
             f"| Amber deep | `{AMBER_DEEP}` | dimmed accent |",
             f"| Bone | `{BONE}` | primary text on dark |",
             f"| Ash | `{ASH}` | secondary text on dark |",
             f"| Outcome green / yellow / red | `{OUTCOME['green']}` / `{OUTCOME['yellow']}` / `{OUTCOME['red']}` | desaturated, always paired with circle / triangle / square |",
             "", "## WCAG contrast check", "",
             "AA needs 4.5:1 for normal text (our 18sp body) and 3:1 for large text (≥ 24sp) and icons.", "",
             "| Pair | Ratio | Needs | Result |", "|---|---|---|---|"]
    ok_all = True
    for label, fg, bg, need in rows:
        c = contrast(fg, bg)
        ok = c >= need
        ok_all &= ok
        lines.append(f"| {label} | {c:.2f}:1 | {need}:1 | {'pass' if ok else '**FAIL**'} |")
    lines += ["", f"Overall: {'all pairs pass' if ok_all else 'SOME PAIRS FAIL — fix Color.kt before shipping'}.", "",
              "Color-blindness: the three outcomes never rely on hue alone; `ResultCard` draws a circle, triangle or",
              "square and the wording says the outcome. Amber vs. sage green are also distinguishable in luminance."]
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------------------------------
# 5. Build everything
# ----------------------------------------------------------------------------------------------
def main() -> None:
    mark = Mark()

    # Mark: SVG in three colors, transparent background
    write(OUT / "foresight_mark.svg", mark.svg(AMBER))
    write(OUT / "foresight_mark_offwhite.svg", mark.svg(BONE))
    write(OUT / "foresight_mark_ink.svg", mark.svg(INK))
    write(OUT / "foresight_mark_square.svg", mark.svg(AMBER, square=True))
    for px in (48, 96, 192, 512, 1024):
        write(OUT / f"foresight_mark_{px}.png", render_png(mark.svg(AMBER, square=True), px))
    write(OUT / "foresight_mark_offwhite_512.png", render_png(mark.svg(BONE, square=True), 512))
    write(OUT / "foresight_mark_ink_512.png", render_png(mark.svg(INK, square=True), 512))
    write(OUT / "foresight_mark_on_ink_1024.png", render_png(mark.svg(AMBER, square=True, background=INK), 1024))

    # Lockups (wordmark outlined from Be Vietnam Pro SemiBold)
    for name, stacked in (("horizontal", False), ("stacked", True)):
        svg = lockup_svg(mark, stacked)
        write(OUT / "lockups" / f"foresight_lockup_{name}.svg", svg)
        w = int(re.search(r'width="(\d+)"', svg).group(1)); h = int(re.search(r'height="(\d+)"', svg).group(1))
        scale = 2048 / w
        write(OUT / "lockups" / f"foresight_lockup_{name}.png", render_png(svg, 2048, int(h * scale)))
        write(OUT / "lockups" / f"foresight_lockup_{name}_on_ink.png",
              render_png(lockup_svg(mark, stacked, background=INK), 2048, int(h * scale)))
        write(OUT / "lockups" / f"foresight_lockup_{name}_light.svg", lockup_svg(mark, stacked, AMBER_DEEP, LIGHT["ink"]))

    # Android adaptive icon: 108dp canvas, mark inside the 66dp safe zone (we use 58dp wide)
    densities = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
    fg_svg = lambda color: (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">'
                            f'{mark.placed(color, 108, 58 / 108)}</svg>')
    legacy_svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48">'
                  f'<rect width="48" height="48" rx="10" fill="{INK}"/>{mark.placed(AMBER, 48, 0.72)}</svg>')
    round_svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48">'
                 f'<circle cx="24" cy="24" r="24" fill="{INK}"/>{mark.placed(AMBER, 48, 0.66)}</svg>')
    for d, m in densities.items():
        write(RES / f"mipmap-{d}" / "ic_launcher_foreground.png", render_png(fg_svg(AMBER), int(108 * m)))
        write(RES / f"mipmap-{d}" / "ic_launcher_monochrome.png", render_png(fg_svg("#FFFFFF"), int(108 * m)))
        write(RES / f"mipmap-{d}" / "ic_launcher.png", render_png(legacy_svg, int(48 * m)))
        write(RES / f"mipmap-{d}" / "ic_launcher_round.png", render_png(round_svg, int(48 * m)))
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@color/ic_launcher_background" />\n'
                '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
                '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
                '</adaptive-icon>\n')
    write(RES / "mipmap-anydpi-v26" / "ic_launcher.xml", adaptive)
    write(RES / "mipmap-anydpi-v26" / "ic_launcher_round.xml", adaptive)
    store = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">'
             f'<rect width="512" height="512" fill="{INK}"/>{mark.placed(AMBER, 512, 0.66)}</svg>')
    write(OUT / "app_icon_store_512.png", render_png(store, 512))

    # Dashboard favicon
    fav = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">'
           f'<rect width="64" height="64" rx="14" fill="{INK}"/>{mark.placed(AMBER, 64, 0.74)}</svg>')
    write(DASH / "favicon.svg", fav)
    write(DASH / "favicon-32.png", render_png(fav, 32))
    write(DASH / "apple-touch-icon.png", render_png(fav, 180))

    # Palette
    write(ROOT / "assets/brand/palette.md", palette_md())

    # Sanity: the 48 px mark must still read as an eye — report its alpha coverage
    img = Image.open(io.BytesIO((OUT / "foresight_mark_48.png").read_bytes())).convert("RGBA")
    coverage = sum(1 for p in img.getdata() if p[3] > 128) / (img.width * img.height)
    print(f"48px mark: {coverage:.0%} of pixels inked (expect roughly 10-25%; a hollow eye is mostly air)")


if __name__ == "__main__":
    main()
